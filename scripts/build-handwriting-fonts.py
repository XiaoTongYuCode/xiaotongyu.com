"""Run after editing handwritten copy: python3 scripts/build-handwriting-fonts.py Caveat.ttf Yozai-Regular.ttf.

Use the upstream Caveat 2.000 and Yozai 0.868 TTFs with fonttools[woff] installed.
"""

import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "public/font"
STYLESHEET = ROOT / "app/_components/site/handwriting-fonts.css"


def read_copy():
    with tempfile.TemporaryDirectory(prefix="handwriting-copy-") as tmp:
        subprocess.run([
            "node", "node_modules/typescript/bin/tsc", "--module", "commonjs",
            "--target", "es2022", "--skipLibCheck", "--rootDir", "app", "--outDir", tmp,
            "app/_i18n/index.ts", "app/_components/home/copy.ts",
        ], check=True, cwd=ROOT)
        return json.loads(subprocess.check_output(["node", "-e", """
const { HOME_COPY } = require(process.argv[1] + '/_components/home/copy.js');
const { I18N_MESSAGES } = require(process.argv[1] + '/_i18n/index.js');
const text = locale => {
  const { hero, content } = I18N_MESSAGES[locale].home;
  return [HOME_COPY[locale].hero.intro, hero.title, content.kicker];
};
const projectTitles = Object.values(I18N_MESSAGES)
  .flatMap(({ home }) => home.work.items.filter(item => item.media).map(item => item.title));
console.log(JSON.stringify({
  en: [...text('en-US'), ...projectTitles].join(''),
  zh: [...text('zh-CN'), HOME_COPY['zh-CN'].about.title].join(''),
}));
""", tmp], text=True, cwd=ROOT))


def build_font(source, text, family, stem, tmp, *, rename=False):
    options = subset.Options(name_IDs=["*"], name_languages=["*"], layout_features=["*"])
    chars = set(map(ord, text))
    with TTFont(source, recalcTimestamp=False) as font:
        if "fvar" in font:
            instantiateVariableFont(font, {"wght": 400}, inplace=True)
        if rename:
            # Yozai reserves its family name for the original font.
            names = {1: family, 3: f"{family} Regular", 4: family, 6: "XTYHandwritingSC-Regular"}
            for entry in font["name"].names:
                if entry.nameID in names:
                    entry.string = names[entry.nameID]
        missing = chars - font.getBestCmap().keys()
        if missing:
            raise ValueError(f"{source.name} lacks: {''.join(map(chr, sorted(missing)))}")
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=chars)
        subsetter.subset(font)
        font.flavor = "woff2"
        font.save(tmp)

    with TTFont(tmp) as built:
        assert set(built.getBestCmap()) == chars
    data = tmp.read_bytes()
    filename = f"{stem}-{hashlib.sha256(data).hexdigest()[:10]}.woff2"
    (FONT_DIR / filename).write_bytes(data)
    print(f"{filename}: {len(chars)} characters, {len(data):,} bytes")
    return filename


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("caveat", type=Path)
    parser.add_argument("yozai", type=Path)
    args = parser.parse_args()
    text = read_copy()
    entries = [
        (args.caveat, text["en"], "Caveat", "caveat-site", False),
        (args.yozai, text["zh"], "XTY Handwriting SC", "xty-handwriting-sc", True),
    ]
    rules = ["/* Generated by scripts/build-handwriting-fonts.py from Caveat and Yozai. */"]
    with tempfile.TemporaryDirectory(prefix="handwriting-fonts-") as tmp:
        for source, copy, family, stem, rename in entries:
            name = build_font(source, copy, family, stem, Path(tmp) / f"{stem}.woff2", rename=rename)
            rules.append(f'''@font-face {{
  font-family: "{family}";
  src: url("/font/{name}") format("woff2");
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}}''')
    STYLESHEET.write_text("\n\n".join(rules) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
